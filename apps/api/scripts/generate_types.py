"""Generate frontend response contracts without starting the app or touching its database."""

import argparse
import inspect
import sys
import types
from enum import Enum
from pathlib import Path
from typing import Any, Literal, Union, get_args, get_origin, get_type_hints

from pydantic import BaseModel

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.schemas import analysis, job, library, resume

modules = [resume, job, library, analysis]
models = {}
for module in modules:
    for name, cls in vars(module).items():
        if (
            inspect.isclass(cls)
            and cls.__module__ == module.__name__
            and issubclass(cls, (BaseModel, Enum))
        ):
            models[name] = cls


def ts_type(annotation):
    origin, args = get_origin(annotation), get_args(annotation)
    if origin in (Union, types.UnionType):
        return " | ".join(ts_type(a) for a in args)
    if origin is list:
        return f"Array<{ts_type(args[0])}>"
    if origin is dict:
        return f"Record<string, {ts_type(args[1])}>"
    if origin is Literal:
        import json

        return " | ".join(json.dumps(a) for a in args)
    if annotation is Any:
        return "unknown"
    if annotation is type(None):
        return "null"
    if annotation is str:
        return "string"
    if annotation in (int, float):
        return "number"
    if annotation is bool:
        return "boolean"
    if inspect.isclass(annotation) and issubclass(annotation, (BaseModel, Enum)):
        return annotation.__name__
    raise TypeError(f"Unsupported contract annotation: {annotation}")


lines = ["// Generated by apps/api/scripts/generate_types.py. Do not edit by hand."]
for name, cls in sorted(models.items()):
    if issubclass(cls, Enum):
        import json

        lines.append(
            f"export const {name} = {{"
            + ", ".join(f"{entry.name}: {json.dumps(entry.value)}" for entry in cls)
            + "} as const;"
        )
        lines.append(f"export type {name} = typeof {name}[keyof typeof {name}];")
    else:
        hints = get_type_hints(cls)
        lines.append(f"export interface {name} {{")
        for field in cls.model_fields:
            optional = (
                "?"
                if (cls.model_fields[field].json_schema_extra or {}).get("typescriptOptional")
                else ""
            )
            lines.append(f"  {field}{optional}: {ts_type(hints[field])};")
        lines.append("}")
lines += [
    "export type ResumeSummary = ResumeSummaryResponse;",
    "export type TargetMarket = 'TR' | 'US' | 'UK' | 'EU' | 'GLOBAL' | 'OTHER';",
]
text = "\n".join(lines) + "\n"
target = Path(__file__).resolve().parents[2] / "web/src/lib/types.ts"
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
if args.check:
    if target.read_text(encoding="utf8") != text:
        raise SystemExit(
            "Frontend contracts are stale. Run uv run python scripts/generate_types.py"
        )
else:
    target.write_text(text, encoding="utf8", newline="\n")
